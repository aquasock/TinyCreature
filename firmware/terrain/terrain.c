/* The art, and the cards drawn from it. A card is an axis-aligned rectangle
 * filled with one tile, its texels written as palette entries from
 * TC_ART_FIRST up, one texel a pixel. Nothing is mixed and the shading table
 * is never consulted, because a texel is already a palette entry: that is why
 * the art's sixty-four entries cannot take colour off the land the way the
 * grey sprite ramp did in entry 28, and why the land's table is untouched by
 * this. The tiles here are drawn at startup rather than converted, which is
 * enough to see the stepping work; tools/convert_tiles.py writes the real
 * ones.
 *
 * The card command is four words: what the tile is and that it is a card, the
 * two corners, and the texel steps across and down. The caller divides the
 * steps out because the fabric has no divider; the fill only accumulates. */

/* The tiles as the fill reads them, one palette-relative index a pixel. */
static const uint8_t *art_tile(uint32_t tile)
{
	if (tile >= ART_TILES)
		return NULL;
	return &ART_PIXELS[tile * TC_TILE_PIXELS];
}

const uint8_t *tc_art_tiles(void)
{
	return ART_PIXELS;
}

unsigned tc_art_tile_count(void)
{
	return ART_TILES;
}

void tc_camera(int32_t *focus_x, int32_t *focus_z, int32_t *eye_x,
	       int32_t *eye_z, int32_t *turn)
{
	*focus_x = cam_focus_x / CELL;
	*focus_z = cam_focus_z / CELL;
	*eye_x = cam_x / CELL;
	*eye_z = cam_z / CELL;
	/* The turn is an angle that a drag adds to without wrapping, so the degree
	 * is taken from the low 16 bits: the readout printed turns past 359 until
	 * the user read one back as 388. */
	*turn = (int32_t)(((uint32_t)cam_turn & 0xffffu) * 360u >> 16);
}
static uint32_t sprite_gx, sprite_gz;   // the cell it stands on
static int32_t sprite_y;                // the ground there, Q4

static void sprite_place(void)
{
	uint32_t best_gx = 0, best_gz = 0;
	int32_t best_d = -1;
	for (uint32_t gz = 0; gz < land->cells_z; gz++)
		for (uint32_t gx = 0; gx < land->cells_x; gx++) {
			/* A cell that draws something is land, and land is where a
			 * creature stands: the middle of the island is water on some
			 * of the six. */
			if (!(land->cells[gz * land->cells_x + gx] & 6))
				continue;
			int32_t dx = (int32_t)gx - (int32_t)land->cells_x / 2;
			int32_t dz = (int32_t)gz - (int32_t)land->cells_z / 2;
			int32_t d = dx * dx + dz * dz;
			if (best_d < 0 || d < best_d) {
				best_d = d;
				best_gx = gx;
				best_gz = gz;
			}
		}
	sprite_gx = best_gx;
	sprite_gz = best_gz;
	sprite_y = height(land->altitude[best_gz * verts_x + best_gx]);
}

// The angle helpers below tc_init only by placement: it seeds the camera the
// mouse will drive, and that camera is described in the same angles.
static int32_t isin(uint32_t a);
static int32_t icos(uint32_t a);

static void camera_from_angles(void);

struct tc_shade tc_init(const struct tc_land *l, void *work)
{
	land = l;
	verts_x = l->cells_x + 1u;
	blocks_x = l->cells_x / BLOCK;
	blocks_z = l->cells_z / BLOCK;
	uint32_t count = verts_x * (l->cells_z + 1u);
	vertices = work;
	for (uint32_t i = 0; i < count; i++)
		vertices[i].stamp = 0;
	generation = 0;
	// Where the mouse picks the camera up when its first report arrives: the
	// scripted orbit's own frame zero, the island's centre looked at from reach
	// away at the orbit's tilt, so that a hand on the mouse moves the view from
	// where the run would have started rather than jumping it.
	cam_turn = 0x8000;
	cam_pitch = PITCH;
	cam_dist = (int32_t)((int64_t)((l->cells_x > l->cells_z ? l->cells_x : l->cells_z) *
				      CELL * 4 / 5) * 16384 / icos(PITCH));
	cam_focus_x = (int32_t)l->cells_x * CELL / 2;
	cam_focus_z = (int32_t)l->cells_z * CELL / 2;
	cam_focus_y = LIFT;
	/* A build with a pin opens looking at it, at the distance that was asked
	 * for, so the first frame shows the card standing where it was put rather
	 * than an island seen from the orbit's reach. */
	if (TC_PIN_SET) {
		int32_t wx, wz;
		pin_world(&wx, &wz);
		cam_focus_x = wx;
		cam_focus_z = wz;
		cam_focus_y = ground(wx, wz);
		cam_dist = TC_PIN_DIST;
	}
	// The camera those four describe, where the frame would put it. tc_draw
	// computes these from them for every driven frame, but a run's first
	// mouse report arrives before the first frame has been drawn, and the
	// pick a middle press makes and the drag's own arithmetic both read them:
	// without this the first report of a run works from a camera at the world
	// origin with no rotation at all.
	camera_from_angles();
	cam_driven = 0;
	last_buttons = 0;
	// The cursor's two shapes, and where it starts: the middle of the screen.
	cursor_build(0);
	cursor_build(1);
	art_build();
	sprite_place();
	cursor_x = TC_WIDTH / 2 * 16;
	cursor_y = TC_HEIGHT / 2 * 16;
	block_low = (uint8_t *)(vertices + count);
	block_high = block_low + blocks_x * blocks_z;
	block_shown = block_high + blocks_x * blocks_z;
	// The shading tables, which every fill reads and main.c hands the fabric.
	uint16_t *pal5 = (uint16_t *)(block_shown + blocks_x * blocks_z);
	uint8_t *lut = (uint8_t *)pal5 + TC_PAL5_BYTES;
	tc_shade_tables(l, pal5, lut);
	shade_pal5 = pal5;
	shade_lut = lut;
	const struct tc_shade shade = {pal5, lut};
	for (uint32_t bz = 0; bz < blocks_z; bz++)
		for (uint32_t bx = 0; bx < blocks_x; bx++) {
			uint8_t low = 255, high = 0, any = 0;
			for (uint32_t z = bz * BLOCK; z <= (bz + 1) * BLOCK; z++)
				for (uint32_t x = bx * BLOCK; x <= (bx + 1) * BLOCK; x++) {
					uint8_t a = l->altitude[z * verts_x + x];
					low = a < low ? a : low;
					high = a > high ? a : high;
					if (z < (bz + 1) * BLOCK && x < (bx + 1) * BLOCK)
						any |= l->cells[z * l->cells_x + x] & 6;
				}
			uint32_t b = bz * blocks_x + bx;
			block_low[b] = low;
			block_high[b] = high;
			// An empty block stays culled for good.
			block_shown[b] = any ? 1 : 0xff;
		}
	return shade;
}

// sin(a), Q14, a in 1/65536 of a turn: a seventh-order odd polynomial on
// each quarter, within 2e-4 of the true value.
static int32_t isin(uint32_t a)
{
	a &= 0xffff;
	uint32_t quarter = a >> 14;
	int64_t x = a & 0x3fff;
	if (quarter & 1)
		x = 0x4000 - x;
	int64_t x2 = x * x >> 14;
	int64_t r = 77;
	r = 1306 - (x2 * r >> 14);
	r = 10584 - (x2 * r >> 14);
	r = 25736 - (x2 * r >> 14);
	int32_t s = (int32_t)(x * r >> 14);
	if (s > 16384)
		s = 16384;
	return quarter & 2 ? -s : s;
}

static int32_t icos(uint32_t a)
{
	return isin(a + 0x4000);
}

// The camera transform: rotate a world point into camera space, Q4. Every
// product and sum here is held in 32 bits, which tc_land_open's grid check is
// what makes safe -- a 64-bit product costs several instructions on the A25
// and this is on the path of every vertex.
static void to_camera(int32_t wx, int32_t wy, int32_t wz, int32_t *x,
		      int32_t *y, int32_t *z)
{
	int32_t dx = wx - cam_x, dy = wy - cam_y, dz = wz - cam_z;
	int32_t rz = (dx * sin_yaw + dz * cos_yaw) >> 14;
	*x = (dx * cos_yaw - dz * sin_yaw) >> 14;
	*y = (dy * cos_pitch + rz * sin_pitch) >> 14;
	*z = (rz * cos_pitch - dy * sin_pitch) >> 14;
}

// The screen position of a camera-space point, Q4: pixels, 16 to a pixel.
static void project_xy(int32_t x, int32_t y, int32_t z, int32_t *sx, int32_t *sy)
{
	int64_t inv = (1 << 30) / z;
	*sx = TC_WIDTH * 8 + (int32_t)(x * inv >> 18);
	*sy = TC_HEIGHT * 8 - (int32_t)(y * inv >> 18);
}

// A stored vertex's camera-space position, recomputed from the grid it
// indexes because the 8-byte record does not keep it. The arithmetic is the
// one vertex() used, so the result is the value it would have stored.
static void vertex_camera(const struct vertex *v, int32_t *x, int32_t *y, int32_t *z)
{
	size_t i = (size_t)(v - vertices);
	uint32_t gz = (uint32_t)(i / verts_x), gx = (uint32_t)(i % verts_x);
	to_camera((int32_t)gx * CELL, height(land->altitude[gz * verts_x + gx]),
		  (int32_t)gz * CELL, x, y, z);
}

static struct vertex *vertex(uint32_t gx, uint32_t gz)
{
	struct vertex *v = &vertices[gz * verts_x + gx];
	if ((v->stamp >> 2) != generation) {
		int32_t x, y, z, sx = 0, sy = 0;
		uint32_t state = VERT_BEHIND;
		to_camera((int32_t)gx * CELL, height(land->altitude[gz * verts_x + gx]),
			  (int32_t)gz * CELL, &x, &y, &z);
		if (z >= NEAR) {
			project_xy(x, y, z, &sx, &sy);
			state = VERT_FRONT;
			if (sx > 32767 || sx < -32768 || sy > 32767 || sy < -32768) {
				// Held clamped and flagged; submit() recomputes it.
				state = VERT_WIDE;
				sx = sx > 32767 ? 32767 : sx < -32768 ? -32768 : sx;
				sy = sy > 32767 ? 32767 : sy < -32768 ? -32768 : sy;
			}
		}
		v->sx = (int16_t)sx;
		v->sy = (int16_t)sy;
		v->stamp = generation << 2 | state;
	}
	return v;
}

void tc_soft_rows(void *ctx, uint32_t first, uint32_t end, uint8_t colour)
{
	struct tc_soft *soft = ctx;
	for (uint32_t r = first; r < end && r < TC_HEIGHT; r++)
		memset(soft->fb + r * soft->stride, colour, TC_WIDTH);
}

// fpga/raster.sv's rule: pixel (i, j) of the screen is filled when, at its
// centre (16 i + 8, 16 j + 8), F = (by - ay)(px - ax) - (bx - ax)(py - ay)
// is >= 0 for each edge a to b; only the bounding box of the corners'
// pixel centres, clamped to the screen, is visited. A filled pixel's colour
// is shade()'s, and S = F0 + F1 + F2 is the same at every pixel of a
// triangle, being the sum of three affine functions whose slopes cancel.
// The weight of the first corner is F1 / S, of the second F2 / S and of the
// third F0 / S, each edge function measuring the far corner from its edge.
void tc_soft_triangle(void *ctx, const int32_t *x, const int32_t *y,
		      uint32_t colours)
{
	struct tc_soft *soft = ctx;
	soft->triangles++;
	int32_t x_lo = x[0], x_hi = x[0], y_lo = y[0], y_hi = y[0];
	for (int k = 1; k < 3; k++) {
		x_lo = x[k] < x_lo ? x[k] : x_lo;
		x_hi = x[k] > x_hi ? x[k] : x_hi;
		y_lo = y[k] < y_lo ? y[k] : y_lo;
		y_hi = y[k] > y_hi ? y[k] : y_hi;
	}
	int32_t i0 = (x_lo + 7) >> 4, i1 = (x_hi - 8) >> 4;
	int32_t j0 = (y_lo + 7) >> 4, j1 = (y_hi - 8) >> 4;
	i0 = i0 < 0 ? 0 : i0;
	j0 = j0 < 0 ? 0 : j0;
	i1 = i1 > TC_WIDTH - 1 ? TC_WIDTH - 1 : i1;
	j1 = j1 > TC_HEIGHT - 1 ? TC_HEIGHT - 1 : j1;
	if (i0 > i1 || j0 > j1)
		return;
	int64_t row[3], step_x[3], step_y[3];
	for (int k = 0; k < 3; k++) {
		int32_t dx = x[(k + 1) % 3] - x[k], dy = y[(k + 1) % 3] - y[k];
		row[k] = (int64_t)dy * (16 * i0 + 8 - x[k]) -
			 (int64_t)dx * (16 * j0 + 8 - y[k]);
		step_x[k] = (int64_t)dy * 16;
		step_y[k] = -(int64_t)dx * 16;
	}
	int64_t s = row[0] + row[1] + row[2];
	int64_t s2 = s << 1, s3 = s + s2;
	for (int32_t j = j0; j <= j1; j++) {
		uint8_t *line = soft->fb + (uint32_t)j * soft->stride;
		int64_t e0 = row[0], e1 = row[1], e2 = row[2];
		for (int32_t i = i0; i <= i1; i++) {
			if ((e0 | e1 | e2) >= 0) {
				int64_t f0 = e0 << 2, f2 = e2 << 2;
				/* A triangle of no area has F all zero, so all
				 * three thresholds pass; its one corner colours
				 * it instead. Inside a real one, F0 + F1 <= S, so
				 * no more than four quarters are ever asked for.*/
				int32_t a = 0, b = 0;
				if (s > 0) {
					a = (f2 >= s) + (f2 >= s2) + (f2 >= s3);
					b = (f0 >= s) + (f0 >= s2) + (f0 >= s3);
				}
				line[i] = shade(soft->pal5, soft->lut, colours, a, b);
				soft->pixels++;
			}
			e0 += step_x[0];
			e1 += step_x[1];
			e2 += step_x[2];
		}
		for (int k = 0; k < 3; k++)
			row[k] += step_y[k];
	}
}

// Clip a convex polygon of n Q4 screen points, in place, to within GUARD of
// the origin on both axes; returns the points left.
static int clip_guard(int32_t *x, int32_t *y, int32_t *wa, int32_t *wb, int n)
{
	for (int side = 0; side < 4 && n; side++) {
		int32_t cx[9], cy[9], ca[9], cb[9];
		int m = 0;
		int32_t sign = side & 2 ? -1 : 1;
		for (int i = 0; i < n; i++) {
			int j = (i + 1) % n;
			// v is the coordinate this side bounds, signed so in is <= GUARD.
			int64_t vp = sign * (int64_t)(side & 1 ? y[i] : x[i]);
			int64_t vq = sign * (int64_t)(side & 1 ? y[j] : x[j]);
			if (vp <= GUARD) {
				cx[m] = x[i];
				cy[m] = y[i];
				ca[m] = wa[i];
				cb[m++] = wb[i];
			}
			if ((vp <= GUARD) != (vq <= GUARD)) {
				int64_t num = GUARD - vp, den = vq - vp;
				cx[m] = x[i] + (int32_t)((int64_t)(x[j] - x[i]) * num / den);
				cy[m] = y[i] + (int32_t)((int64_t)(y[j] - y[i]) * num / den);
				// A cut vertex's colour is the two it cuts mixed at
				// the same fraction, in the quarters the fill uses.
				ca[m] = (int32_t)(((int64_t)wa[i] * (den - num) +
						   (int64_t)wa[j] * num + den / 2) / den);
				cb[m] = (int32_t)(((int64_t)wb[i] * (den - num) +
						   (int64_t)wb[j] * num + den / 2) / den);
				if (side & 1)
					cy[m] = sign * GUARD;
				else
					cx[m] = sign * GUARD;
				m++;
			}
		}
		n = m;
		memcpy(x, cx, sizeof(int32_t) * (size_t)m);
		memcpy(y, cy, sizeof(int32_t) * (size_t)m);
		memcpy(wa, ca, sizeof(int32_t) * (size_t)m);
		memcpy(wb, cb, sizeof(int32_t) * (size_t)m);
	}
	return n;
}

// One triangle facing up, its corners counter-clockwise seen from above:
// send it if it faces the camera and reaches the screen. Front faces wind
// clockwise on the screen (y down), which is the order that makes the
// rasterizer's edge functions >= 0 inside.
static void emit(const int32_t *x, const int32_t *y, uint32_t colours)
{
	int64_t cross = (int64_t)(x[1] - x[0]) * (y[2] - y[0]) -
			(int64_t)(y[1] - y[0]) * (x[2] - x[0]);
	if (cross >= 0)
		return;
	int32_t x_lo = x[0], x_hi = x[0], y_lo = y[0], y_hi = y[0];
	for (int i = 1; i < 3; i++) {
		x_lo = x[i] < x_lo ? x[i] : x_lo;
		x_hi = x[i] > x_hi ? x[i] : x_hi;
		y_lo = y[i] < y_lo ? y[i] : y_lo;
		y_hi = y[i] > y_hi ? y[i] : y_hi;
	}
	// No pixel centre on the screen in its box: the rasterizer would fill
	// nothing, so it is not sent.
	if (((x_lo + 7) >> 4) > ((x_hi - 8) >> 4) || x_hi < 8 ||
	    x_lo + 7 >= TC_WIDTH * 16 || ((y_lo + 7) >> 4) > ((y_hi - 8) >> 4) ||
	    y_hi < 8 || y_lo + 7 >= TC_HEIGHT * 16)
		return;
	out->triangle(out->ctx, x, y, colours);
	counts->triangles++;
}

// The slow side of submit(): a corner whose screen position the 8-byte
// record could not hold exactly, or one that reached past the guard band.
// Recomputes camera space from the grid where it is needed, clips at the
// near plane, and fans the result.
static void submit_slow(const struct vertex *a, const struct vertex *b,
			const struct vertex *c, uint32_t colours)
{
	const struct vertex *in[3] = {a, b, c};
	uint32_t state[3];
	int32_t x[3] = {0, 0, 0}, y[3] = {0, 0, 0}, z[3] = {0, 0, 0};
	int32_t sx[3] = {0, 0, 0}, sy[3] = {0, 0, 0};
	// The first corner's colour is what is left after the other two, so a
	// polygon vertex needs only their two weights, in quarters.
	int32_t wa[3] = {0, 4, 0}, wb[3] = {0, 0, 4};
	int behind = 0;
	for (int i = 0; i < 3; i++) {
		state[i] = in[i]->stamp & 3u;
		if (state[i] == VERT_FRONT) {
			sx[i] = in[i]->sx;
			sy[i] = in[i]->sy;
			continue;
		}
		vertex_camera(in[i], &x[i], &y[i], &z[i]);
		if (state[i] == VERT_BEHIND)
			behind++;
		else
			project_xy(x[i], y[i], z[i], &sx[i], &sy[i]);
	}
	if (behind == 3)
		return;
	if (behind) {
		// Clipping interpolates along the edges, so every corner needs its
		// camera-space position, including the ones the record held exactly.
		for (int i = 0; i < 3; i++)
			if (state[i] == VERT_FRONT)
				vertex_camera(in[i], &x[i], &y[i], &z[i]);
	}
	int32_t px[9], py[9], pa[9], pb[9];
	int n = 0;
	if (!behind) {
		for (int i = 0; i < 3; i++) {
			px[n] = sx[i];
			py[n] = sy[i];
			pa[n] = wa[i];
			pb[n++] = wb[i];
		}
	} else {
		for (int i = 0; i < 3; i++) {
			int j = (i + 1) % 3;
			if (z[i] >= NEAR) {
				px[n] = sx[i];
				py[n] = sy[i];
				pa[n] = wa[i];
				pb[n++] = wb[i];
			}
			if ((z[i] >= NEAR) != (z[j] >= NEAR)) {
				int64_t num = NEAR - z[i], den = z[j] - z[i];
				int32_t cx = x[i] + (int32_t)((x[j] - x[i]) * num / den);
				int32_t cy = y[i] + (int32_t)((y[j] - y[i]) * num / den);
				int32_t qx, qy;
				project_xy(cx, cy, NEAR, &qx, &qy);
				px[n] = qx;
				py[n] = qy;
				pa[n] = (int32_t)(((int64_t)wa[i] * (den - num) +
						   (int64_t)wa[j] * num + den / 2) / den);
				pb[n] = (int32_t)(((int64_t)wb[i] * (den - num) +
						   (int64_t)wb[j] * num + den / 2) / den);
				n++;
			}
		}
	}
	for (int i = 0; i < n; i++)
		if (px[i] < -GUARD || px[i] > GUARD || py[i] < -GUARD || py[i] > GUARD) {
			n = clip_guard(px, py, pa, pb, n);
			break;
		}
	for (int k = 1; k + 1 < n; k++) {
		int32_t tx[3] = {px[0], px[k], px[k + 1]};
		int32_t ty[3] = {py[0], py[k], py[k + 1]};
		uint32_t corner[3];
		const int32_t at[3] = {0, k, k + 1};
		for (int i = 0; i < 3; i++)
			corner[i] = shade(shade_pal5, shade_lut, colours,
					  pa[at[i]], pb[at[i]]);
		emit(tx, ty, corner[0] | corner[1] << 8 | corner[2] << 16);
	}
}

// Draw one triangle facing up. The walk's everyday case -- every corner in
// front of the near plane with an exact screen position inside the guard
// band, which is every triangle of the orbit the board draws -- is taken
// straight from the record, with none of the clip machinery's stack; a
// corner beyond the guard band falls through to submit_slow().
static void submit(const struct vertex *a, const struct vertex *b,
		   const struct vertex *c, uint32_t colours)
{
	if (!(a->stamp & 3u) && !(b->stamp & 3u) && !(c->stamp & 3u)) {
		int32_t x[3] = {a->sx, b->sx, c->sx};
		int32_t y[3] = {a->sy, b->sy, c->sy};
		int i;
		for (i = 0; i < 3; i++)
			if (x[i] < -GUARD || x[i] > GUARD || y[i] < -GUARD || y[i] > GUARD)
				break;
		if (i == 3) {
			emit(x, y, colours);
			return;
		}
	}
	submit_slow(a, b, c, colours);
}

static int outside(int32_t x, int32_t y, int32_t z)
{
	int64_t z5 = (int64_t)z * 5, z45 = (int64_t)z * 45;
	return (z < NEAR) | ((int64_t)x * 8 < -z5) << 1 | ((int64_t)x * 8 > z5) << 2 |
	       ((int64_t)y * 128 > z45) << 3 | ((int64_t)y * 128 < -z45) << 4;
}

static void cull_blocks(void)
{
	for (uint32_t bz = 0; bz < blocks_z; bz++)
		for (uint32_t bx = 0; bx < blocks_x; bx++) {
			uint32_t b = bz * blocks_x + bx;
			if (block_shown[b] == 0xff)
				continue;
			int all = 0x1f;
			for (int k = 0; k < 8 && all; k++) {
				int32_t x, y, z;
				to_camera((int32_t)(bx + (k & 1)) * BLOCK * CELL,
					  height(k & 2 ? block_high[b] : block_low[b]),
					  (int32_t)(bz + (k >> 2 & 1)) * BLOCK * CELL,
					  &x, &y, &z);
				all &= outside(x, y, z);
			}
			block_shown[b] = all ? 0 : 1;
		}
}

static int32_t floor_div(int32_t a, int32_t b)
{
	return a >= 0 ? a / b : -((-a + b - 1) / b);
}

static void draw_cell(uint32_t gx, uint32_t gz)
{
	const uint8_t *cell = &land->cells[gz * land->cells_x + gx];
	uint8_t flags = cell[0];
	if (!(flags & 6))
		return;
	counts->cells++;
	struct vertex *tl = vertex(gx, gz), *tr = vertex(gx + 1, gz);
	struct vertex *bl = vertex(gx, gz + 1), *br = vertex(gx + 1, gz + 1);
	// Each corner carries its own colour, and they are handed over in the
	// order the corners are, which is the order the fill shades between.
	uint32_t ctl = land->colour[gz * verts_x + gx];
	uint32_t ctr = land->colour[gz * verts_x + gx + 1];
	uint32_t cbl = land->colour[(gz + 1) * verts_x + gx];
	uint32_t cbr = land->colour[(gz + 1) * verts_x + gx + 1];
	int32_t px = cam_x - (int32_t)gx * CELL, pz = cam_z - (int32_t)gz * CELL;
	const struct vertex *t[2][3];
	uint32_t c[2][3];
	int far;
	if (flags & 1) {
		t[0][0] = bl, t[0][1] = tl, t[0][2] = tr;
		t[1][0] = bl, t[1][1] = tr, t[1][2] = br;
		c[0][0] = cbl, c[0][1] = ctl, c[0][2] = ctr;
		c[1][0] = cbl, c[1][1] = ctr, c[1][2] = cbr;
		far = px + pz > CELL ? 0 : 1;
	} else {
		t[0][0] = tl, t[0][1] = tr, t[0][2] = br;
		t[1][0] = tl, t[1][1] = br, t[1][2] = bl;
		c[0][0] = ctl, c[0][1] = ctr, c[0][2] = cbr;
		c[1][0] = ctl, c[1][1] = cbr, c[1][2] = cbl;
		far = px < pz ? 0 : 1;
	}
	for (int k = 0; k < 2; k++) {
		int i = k ? 1 - far : far;
		if (flags & (2 << i))
			submit(t[i][0], t[i][1], t[i][2],
			       c[i][0] | c[i][1] << 8 | c[i][2] << 16);
	}
}

// The next of lo..hi, whichever is farther from c, toward c.
static uint32_t farther(int32_t *lo, int32_t *hi, int32_t c)
{
	int32_t a = c - *lo, b = *hi - c;
	if ((a < 0 ? -a : a) >= (b < 0 ? -b : b))
		return (uint32_t)(*lo)++;
	return (uint32_t)(*hi)--;
}

// The land's height under a world position, Q4, clamped to the island: the
// camera's focus follows the ground it is dragged over.
static int32_t ground(int32_t x, int32_t z)
{
	int32_t gx = x / CELL, gz = z / CELL;
	if (gx < 0)
		gx = 0;
	if (gz < 0)
		gz = 0;
	if (gx > (int32_t)land->cells_x)
		gx = (int32_t)land->cells_x;
	if (gz > (int32_t)land->cells_z)
		gz = (int32_t)land->cells_z;
	return height(land->altitude[(uint32_t)gz * verts_x + (uint32_t)gx]);
}

// The land under a point on the screen, Q4: the camera and the projection
// undone and marched against the height field the renderer draws. This is
// what the middle button needs, because the original takes the piece of land
// under the hand as the point it turns the camera about (core-reference
// OB-005), and it is the same pick a double click would need to fly
// somewhere. Returns 0 when the ray leaves the island without meeting it.
static int land_pick(int32_t sx, int32_t sy, int32_t *px, int32_t *py, int32_t *pz)
{
	int32_t extent = (int32_t)(land->cells_x > land->cells_z ? land->cells_x
								: land->cells_z) * CELL;
	int32_t limit_x = (int32_t)land->cells_x * CELL;
	int32_t limit_z = (int32_t)land->cells_z * CELL;
	for (int32_t z = NEAR; z < extent * 3; z += 16) {
		int32_t cx = (int32_t)(((int64_t)(sx - TC_WIDTH * 8) * z) >> 12);
		int32_t cy = (int32_t)(((int64_t)(TC_HEIGHT * 8 - sy) * z) >> 12);
		// Undo the two rotations to_camera applies, against them and in the
		// reverse order, so the point is the one that projects here.
		int32_t dy = (int32_t)(((int64_t)cy * cos_pitch -
					(int64_t)z * sin_pitch) >> 14);
		int32_t rz = (int32_t)(((int64_t)cy * sin_pitch +
					(int64_t)z * cos_pitch) >> 14);
		int32_t dx = (int32_t)(((int64_t)cx * cos_yaw +
					(int64_t)rz * sin_yaw) >> 14);
		int32_t dz = (int32_t)((-(int64_t)cx * sin_yaw +
					(int64_t)rz * cos_yaw) >> 14);
		int32_t x = cam_x + dx, y = cam_y + dy, wz = cam_z + dz;
		if (x < 0 || x > limit_x || wz < 0 || wz > limit_z)
			continue;
		int32_t h = ground(x, wz);
		if (y <= h) {
			*px = x;
			*py = h;
			*pz = wz;
			return 1;
		}
	}
	return 0;
}

// Put the camera where the focus, the angle, the tilt and the distance say,
// clear of the ground it is looking at. Every driven frame does this, and so
// does the input: a grab has to project the point it holds through the camera
// the report was applied to, not the frame before it, or the hand trails the
// land by a frame.
static void camera_from_angles(void)
{
	sin_yaw = isin((uint32_t)cam_turn);
	cos_yaw = icos((uint32_t)cam_turn);
	sin_pitch = isin((uint32_t)cam_pitch);
	cos_pitch = icos((uint32_t)cam_pitch);
	int32_t horiz = (int32_t)((int64_t)cam_dist * cos_pitch >> 14);
	cam_x = cam_focus_x - (int32_t)((int64_t)horiz * sin_yaw >> 14);
	cam_z = cam_focus_z - (int32_t)((int64_t)horiz * cos_yaw >> 14);
	cam_y = cam_focus_y + (int32_t)((int64_t)cam_dist * sin_pitch >> 14);
	// The camera stays clear of the ground it is looking at, which is what
	// keeps a drag over a hill from burying it (core-reference OB-005).
	int32_t clearance = ground(cam_x, cam_z) + 160;
	if (cam_y < clearance)
		cam_y = clearance;
}

void tc_mouse(uint8_t buttons, int32_t dx, int32_t dy, int32_t wheel)
{
	/* The camera the scripted orbit left in the same variables, so that the
	 * first report takes the view up where it is rather than jumping it. */
	if (!cam_driven)
		cam_driven = 1;

	/* The cursor follows the hand whatever the buttons are doing, so that a
	 * drag keeps hold of the piece of land it took. */
	cursor_x += dx * 16;
	cursor_y += dy * 16;
	if (cursor_x < 0)
		cursor_x = 0;
	if (cursor_y < 0)
		cursor_y = 0;
	if (cursor_x > (TC_WIDTH - 1) * 16)
		cursor_x = (TC_WIDTH - 1) * 16;
	if (cursor_y > (TC_HEIGHT - 1) * 16)
		cursor_y = (TC_HEIGHT - 1) * 16;

	/* The middle button takes hold of the piece of land under the hand, the
	 * way the original does: that point becomes what the camera looks at and
	 * the point it turns about, at the distance it was from the camera when
	 * the button went down, so the land under the hand holds still while
	 * everything else swings around it (core-reference OB-005).
	 *
	 * The distance is the grabbed point's depth along the view, which is the
	 * projection of the camera's own axis on the way to it: the camera keeps
	 * its angle and only re-anchors, so what follows is an orbit of that
	 * point and not of the old focus. A press that misses the island leaves
	 * the button doing nothing at all, which is also the original's rule. */
	if ((buttons & TC_MOUSE_MIDDLE) && !(last_buttons & TC_MOUSE_MIDDLE)) {
		int32_t px, py, pz;
		if (land_pick(cursor_x, cursor_y, &px, &py, &pz)) {
			int32_t depth = (int32_t)(((int64_t)(px - cam_x) * (cos_pitch * sin_yaw >> 14) +
						   (int64_t)(py - cam_y) * -sin_pitch +
						   (int64_t)(pz - cam_z) * (cos_pitch * cos_yaw >> 14)) >> 14);
			int32_t far = (int32_t)((land->cells_x > land->cells_z ? land->cells_x
									      : land->cells_z) * CELL * 2);
			if (depth < 160)
				depth = 160;   /* ten units: the floor the original keeps */
			if (depth > far)
				depth = far;
			cam_focus_x = px;
			cam_focus_y = py;
			cam_focus_z = pz;
			cam_dist = depth;
		}
	}

	/* A left press on the land takes hold of it. The point under the hand is
	 * the thing the hand is holding, and while the button stays down the hand
	 * is drawn where that point projects, so it slides with the land it took
	 * and reads as holding it. The original's hand is a thing in the world
	 * holding one piece of it for a whole drag -- openblack's recorded left
	 * drag has the same grabbed point on all 400 of its held frames -- and not
	 * a pointer that follows the mouse: its screen position is whatever the
	 * projection says. What the mouse moves is still the camera, so the land
	 * follows the hand the way the tuned drag has it. */
	if (left_grab && !(buttons & TC_MOUSE_LEFT))
		left_grab = 0;
	if ((buttons & TC_MOUSE_LEFT) && !(last_buttons & TC_MOUSE_LEFT)) {
		int32_t px, py, pz;
		if (land_pick(cursor_x, cursor_y, &px, &py, &pz)) {
			grab_x = px;
			grab_y = py;
			grab_z = pz;
			left_grab = 1;
		}
	}

	/* While the middle button is held the hand stays on the middle of the
	 * screen, which is the finger holding the earth: the piece of land it
	 * took is what the camera turns about, and the aim puts that point at
	 * the middle of the screen, so the fingertip and the land it holds stay
	 * in the same place while everything else swings. It snaps there as the
	 * button goes down -- after the pick above, which uses where the hand
	 * was -- and only follows the mouse again when the button comes up. The
	 * original recentres the pointer on every frame of a rotation the same
	 * way (core-reference OB-005). */
	if (buttons & TC_MOUSE_MIDDLE) {
		cursor_x = TC_WIDTH / 2 * 16;
		cursor_y = TC_HEIGHT / 2 * 16;
	}

	if (buttons & TC_MOUSE_MIDDLE) {
		/* Turning: the angle moves with the drag and the tilt against it,
		 * which is what makes dragging down look further down. */
		cam_turn += dx * TC_TURN_PER_COUNT;
		cam_pitch -= dy * TC_PITCH_PER_COUNT;
		if (cam_pitch < 4096)
			cam_pitch = 4096;      /* about nine degrees: never flat */
		if (cam_pitch > 0x3800)
			cam_pitch = 0x3800;    /* about seventy-nine: never straight down */
	} else if (buttons & TC_MOUSE_LEFT) {
		/* The land follows the hand: a count covers this much of it at
		 * this distance, and the focus moves against the drag. Pulling the
		 * land down moves the focus forward, which takes more world for
		 * the same count because the ground is seen at a tilt. */
		int32_t per = cam_dist / TC_DRAG_DIVISOR;
		int32_t ax = -(per * dx);
		int32_t az = (int32_t)((int64_t)per * dy * 16384 / cos_pitch);
		cam_focus_x += (int32_t)(((int64_t)ax * cos_yaw +
					  (int64_t)az * sin_yaw) >> 14);
		cam_focus_z += (int32_t)((-(int64_t)ax * sin_yaw +
					  (int64_t)az * cos_yaw) >> 14);
		if (cam_focus_x < 0)
			cam_focus_x = 0;
		if (cam_focus_z < 0)
			cam_focus_z = 0;
		if (cam_focus_x > (int32_t)land->cells_x * CELL)
			cam_focus_x = (int32_t)land->cells_x * CELL;
		if (cam_focus_z > (int32_t)land->cells_z * CELL)
			cam_focus_z = (int32_t)land->cells_z * CELL;
		cam_focus_y = ground(cam_focus_x, cam_focus_z);
	}

	if (wheel) {
		/* Rolling towards the hand pulls the camera back, which is the other
		 * way round from the usual direction: this user asked for it when the
		 * mouse first reached the board, had it turned round once to try the
		 * usual way, and asked for this back. */
		cam_dist -= wheel * TC_ZOOM_PER_COUNT;
		if (cam_dist < 320)
			cam_dist = 320;              /* twenty units: in the grass */
		if (cam_dist > (int32_t)((land->cells_x > land->cells_z ?
					  land->cells_x : land->cells_z) * CELL * 2))
			cam_dist = (int32_t)((land->cells_x > land->cells_z ?
					      land->cells_x : land->cells_z) * CELL * 2);
	}

	/* The hand goes where the land it holds is drawn, which is the whole of
	 * the grab: it is the land that is held, not the mouse. The camera is put
	 * where this report left it before the point is projected, so the hand and
	 * the land it is holding are in step within the frame rather than a frame
	 * apart. */
	if (left_grab) {
		int32_t ax, ay, az, sx, sy;
		camera_from_angles();
		to_camera(grab_x, grab_y, grab_z, &ax, &ay, &az);
		if (az > NEAR) {
			project_xy(ax, ay, az, &sx, &sy);
			if (sx < 0)
				sx = 0;
			if (sy < 0)
				sy = 0;
			if (sx > (TC_WIDTH - 1) * 16)
				sx = (TC_WIDTH - 1) * 16;
			if (sy > (TC_HEIGHT - 1) * 16)
				sy = (TC_HEIGHT - 1) * 16;
			cursor_x = sx;
			cursor_y = sy;
		}
	}
	/* Which buttons these were, once every edge above has been read, so that
	 * the next report knows what this one was, and so that the cursor can
	 * draw the frame's sprite or the crosshair. */
	last_buttons = buttons;
	cursor_buttons = buttons;
}

// One run of the cursor as the two triangles a rectangle needs, wound the way
// the rasterizer's edge functions want: the interior has to lie to the left of
// each directed edge, which on a screen whose y runs downwards is down the
// left side, along the bottom, and back along the diagonal.
static void hand_rect(int32_t x0, int32_t y0, int32_t x1, int32_t y1,
		      uint8_t colour)
{
	int32_t x[3], y[3];
	uint32_t colours = colour * 0x010101u;

	x[0] = x0; y[0] = y0;
	x[1] = x0; y[1] = y1;
	x[2] = x1; y[2] = y1;
	out->triangle(out->ctx, x, y, colours);
	counts->triangles++;
	x[0] = x0; y[0] = y0;
	x[1] = x1; y[1] = y1;
	x[2] = x1; y[2] = y0;
	out->triangle(out->ctx, x, y, colours);
	counts->triangles++;
}

/* A card, as fpga/raster.sv fills one and from the same fields: the
 * accumulators carry, one add a pixel, and the texel is the top five bits of
 * each, so neither side divides. The texel is written as a palette entry from
 * TC_ART_FIRST up, and nothing is mixed or looked up. */
void tc_soft_card(void *soft, const struct tc_card *c)
{
	struct tc_soft *s = soft;
	const uint8_t *art = art_tile(c->tile);
	if (art == NULL || c->i0 >= c->i1 || c->j0 >= c->j1)
		return;
	uint32_t v = c->v0;
	for (uint32_t j = c->j0; j < c->j1; j++, v += c->dv) {
		uint8_t *row = s->fb + (size_t)j * s->stride;
		uint32_t u = c->u0;
		for (uint32_t i = c->i0; i < c->i1; i++, u += c->du) {
			row[i] = (uint8_t)(TC_ART_FIRST +
					   art[(v >> 8) * 32 + (u >> 8)]);
			s->pixels++;
		}
	}
}

/* The camera readout: where the eye and its focus are, in the island's own
 * cells, and which way it looks, along the bottom of the frame. This
 * renderer has rectangles and no font, and a seven-segment digit is seven of
 * them, so the readout is a few dozen rectangles and no fabric work at all.
 * It is drawn only when a mouse is driving the camera: a scripted run draws
 * the frames this project recorded and a readout in them would move every one
 * of those frame CRCs. */
#ifndef TC_READOUT
#define TC_READOUT 1
#endif

#if TC_READOUT
/* Which of the seven segments each digit lights, a bit each. */
static const uint8_t seg_digits[10] = {
	0x3f, 0x06, 0x5b, 0x4f, 0x66, 0x6d, 0x7d, 0x07, 0x7f, 0x6f
};
/* The segments as lines of a cell two wide and three tall, in the order the
 * bits are: a the top, b upper right, c lower right, d the bottom, e lower
 * left, f upper left, g the middle. */
static const int8_t seg_lines[7][4] = {
	{0, 0, 2, 0}, {2, 0, 2, 1}, {2, 1, 2, 2}, {0, 2, 2, 2},
	{0, 1, 0, 2}, {0, 0, 0, 1}, {0, 1, 2, 1},
};

static void readout_digit(uint32_t digit, int32_t x, int32_t y, int32_t w,
			  int32_t h, int32_t t, uint8_t colour)
{
	for (unsigned s = 0; s < 7; s++) {
		if (!(seg_digits[digit] >> s & 1))
			continue;
		int32_t x0 = x + seg_lines[s][0] * w / 2;
		int32_t y0 = y + seg_lines[s][1] * h / 2;
		int32_t x1 = x + seg_lines[s][2] * w / 2;
		int32_t y1 = y + seg_lines[s][3] * h / 2;
		if (y0 == y1)
			hand_rect(x0, y0 - t / 2, x1, y0 + t / 2, colour);
		else
			hand_rect(x0 - t / 2, y0, x0 + t / 2, y1, colour);
	}
}

/* One number, three digits, with a column of its own for a minus so that an
 * eye swung off the island still reads as the negative cell it is. */
static void readout_number(int32_t value, int32_t *x, int32_t y, int32_t w,
			   int32_t h, int32_t t, uint8_t colour)
{
	uint32_t magnitude = value < 0 ? (uint32_t)(-(int64_t)value)
				       : (uint32_t)value;
	int32_t mid = y + h / 2;
	if (value < 0)
		hand_rect(*x, mid - t / 2, *x + w, mid + t / 2, colour);
	*x += w + t;
	for (int32_t scale = 100; scale >= 1; scale /= 10) {
		readout_digit(magnitude / (uint32_t)scale % 10, *x, y, w, h, t,
			      colour);
		*x += w + t;
	}
}

static void draw_readout(void)
{
	if (!cam_driven)
		return;
	int32_t fx, fz, ex, ez, turn;
	tc_camera(&fx, &fz, &ex, &ez, &turn);
	const int32_t w = 96, h = 144, t = 32;   // six by nine pixels, two thick
	const int32_t y = (TC_HEIGHT - 11) * 16;
	int32_t x = 2 * 16;
	/* The focus in the cursor's green and the eye in its red, so which pair
	 * is which does not need a label. */
	readout_number(fx, &x, y, w, h, t, TC_CURSOR_IDLE);
	readout_number(fz, &x, y, w, h, t, TC_CURSOR_IDLE);
	x += 2 * 16;
	readout_number(ex, &x, y, w, h, t, TC_CURSOR_HELD);
	readout_number(ez, &x, y, w, h, t, TC_CURSOR_HELD);
	x += 2 * 16;
	readout_number(turn, &x, y, w, h, t, TC_SEA_COLOUR);
}
#else
static void draw_readout(void)
{
}
#endif

// The sprite, as runs of one colour a row, each run the rectangle hand_rect
// wants. Its base is the middle of the cell it stands on, at the ground
// there, and its top is TC_SPRITE_UNITS above it: those two projections give
// the height the camera makes of it, and the width follows from the header's
// cell count, so the sprite shrinks with distance and grows as the wheel comes
// in.
static void draw_sprite(void)
{
#if TC_SPRITE_DRAW
	const int32_t wx = (int32_t)sprite_gx * CELL + CELL / 2;
	const int32_t wz = (int32_t)sprite_gz * CELL + CELL / 2;
	int32_t x, y, z, sx0, sy0, sx1, sy1;
	to_camera(wx, sprite_y, wz, &x, &y, &z);
	if (z < NEAR)
		return;
	project_xy(x, y, z, &sx0, &sy0);
	to_camera(wx, sprite_y + TC_SPRITE_UNITS, wz, &x, &y, &z);
	if (z < NEAR)
		return;
	project_xy(x, y, z, &sx1, &sy1);
	const int32_t h = sy0 - sy1;
	if (h <= 0)
		return;
	const int32_t w = (int32_t)((int64_t)h * TC_SPRITE_CELLS_X / TC_SPRITE_CELLS_Y);
	const int32_t left = sx0 - w / 2;
	const int32_t top = sy0 - h;
	for (int32_t row = 0; row < TC_SPRITE_CELLS_Y; row++) {
		int32_t col = 0;
		while (col < TC_SPRITE_CELLS_X) {
			const uint8_t v = tc_sprite_cells[row * TC_SPRITE_CELLS_X + col];
			if (v == TC_SPRITE_EMPTY) {
				col++;
				continue;
			}
			const int32_t start = col;
			while (col < TC_SPRITE_CELLS_X &&
			       tc_sprite_cells[row * TC_SPRITE_CELLS_X + col] == v)
				col++;
			hand_rect(left + w * start / TC_SPRITE_CELLS_X,
				  top + h * row / TC_SPRITE_CELLS_Y,
				  left + w * col / TC_SPRITE_CELLS_X,
				  top + h * (row + 1) / TC_SPRITE_CELLS_Y,
				  (uint8_t)(TC_SPRITE_FIRST + v));
		}
	}
#endif
}

/* One card, standing on the land at a world position: three cells tall and as
 * wide as it is tall, its base at wy and its top three cells up, filled with
 * one tile of the art. The rectangle's pixel range, clamped to the screen, and
 * the fields the fabric wants are worked out here because it has no divider:
 * the steps in Q8 texels a pixel, and what the first pixel of each row and
 * column stands at. A pixel centre is 16i + 8, which is the rule both fills
 * use. The shelf and the pin both come through here, so there is one copy of
 * this arithmetic. */
static void card_at(int32_t wx, int32_t wy, int32_t wz, uint32_t tile)
{
	if (out->card == NULL)
		return;
	int32_t x, y, z, sx0, sy0, sx1, sy1;
	to_camera(wx, wy, wz, &x, &y, &z);
	if (z < NEAR)
		return;
	project_xy(x, y, z, &sx0, &sy0);
	to_camera(wx, wy + 3 * CELL, wz, &x, &y, &z);
	if (z < NEAR)
		return;
	project_xy(x, y, z, &sx1, &sy1);
	int32_t h = sy0 - sy1;
	if (h < 16)
		return;
	int32_t w = h;
	struct tc_card card;
	int32_t ci0 = floor_div(sx0 - w / 2 - 8 + 15, 16);
	int32_t ci1 = floor_div(sx0 + w / 2 - 8 + 15, 16);
	int32_t cj0 = floor_div(sy1 - 8 + 15, 16);
	int32_t cj1 = floor_div(sy0 - 8 + 15, 16);
	if (ci0 < 0)
		ci0 = 0;
	if (cj0 < 0)
		cj0 = 0;
	if (ci1 > TC_WIDTH)
		ci1 = TC_WIDTH;
	if (cj1 > TC_HEIGHT)
		cj1 = TC_HEIGHT;
	if (ci0 >= ci1 || cj0 >= cj1)
		return;
	const int32_t bx0 = sx0 - w / 2, by0 = sy1;
	card.tile = tile;
	card.i0 = (uint32_t)ci0;
	card.i1 = (uint32_t)ci1;
	card.j0 = (uint32_t)cj0;
	card.j1 = (uint32_t)cj1;
	card.du = (uint32_t)((32 << 12) / w);
	card.dv = (uint32_t)((32 << 12) / h);
	card.u0 = (uint32_t)(((ci0 * 16 + 8 - bx0) * (int32_t)card.du) >> 4);
	card.v0 = (uint32_t)(((cj0 * 16 + 8 - by0) * (int32_t)card.dv) >> 4);
	out->card(out->ctx, &card);
}

void tc_draw(const struct tc_target *target, uint32_t frame, uint32_t frames,
	     struct tc_stats *stats)
{
	out = target;
	counts = stats;
	stats->triangles = 0;
	stats->cells = 0;
	generation++;

	// One orbit, swinging in to 40% and back out twice on the way round.
	int32_t size = (land->cells_x > land->cells_z ? land->cells_x : land->cells_z) * CELL;
	int32_t reach = size * 4 / 5;
	if (!cam_driven) {
		if (TC_PIN_SET) {
			/* A pinned build stands still on its pin until the mouse takes
			 * the camera, so that what it opens on is the card it was
			 * asked to stand there. */
			camera_from_angles();
		} else {
			uint32_t turn = (uint32_t)((uint64_t)frame * 65536 / frames);
			int32_t radius = (int32_t)(reach * (7 * 16384 + 3 * (int64_t)icos(2 * turn)) / (10 * 16384));
			cam_x = land->cells_x * CELL / 2 + (int32_t)((int64_t)radius * isin(turn) >> 14);
			cam_z = land->cells_z * CELL / 2 + (int32_t)((int64_t)radius * icos(turn) >> 14);
			cam_y = (int32_t)((int64_t)radius * TAN_PITCH >> 14) + LIFT;
			sin_yaw = isin(turn + 0x8000);
			cos_yaw = icos(turn + 0x8000);
			sin_pitch = isin(PITCH);
			cos_pitch = icos(PITCH);
			// The same camera written as the focus, angle, tilt and distance the
			// mouse drives, so its first report can take it over in place.
			cam_turn = (int32_t)(turn + 0x8000);
			cam_pitch = PITCH;
			cam_dist = (int32_t)((int64_t)radius * 16384 / cos_pitch);
			cam_focus_x = cam_x + (int32_t)((int64_t)radius * sin_yaw >> 14);
			cam_focus_z = cam_z + (int32_t)((int64_t)radius * cos_yaw >> 14);
			cam_focus_y = cam_y - (int32_t)((int64_t)radius * TAN_PITCH >> 14);
		}
	} else {
		camera_from_angles();
	}

	/* A board build times each phase with the core's cycle counter. The host
	 * twin carries no clock, so this is the board's profile alone. */
	const int timed = out->now != NULL && out->phase != NULL;
	uint64_t phase_at = timed ? out->now() : 0;

	// The sky above the horizon, the sea below it, a run of rows at a time.
	int32_t horizon = TC_HEIGHT / 2 - FOCAL * sin_pitch / cos_pitch;
	uint32_t run = 0, run_colour = 0;
	for (int32_t r = 0; r <= TC_HEIGHT; r++) {
		uint32_t c = 0;
		if (r == TC_HEIGHT)
			c = 0x100;
		else if (r < horizon)
			c = TC_SKY_COLOUR + (uint32_t)(r * TC_RAMP / horizon);
		else
			c = TC_SEA_COLOUR + TC_RAMP - 1;   /* the deepest sea, one blue */
		if (r && c != run_colour) {
			target->rows(target->ctx, run, (uint32_t)r, (uint8_t)run_colour);
			run = (uint32_t)r;
		}
		run_colour = c;
	}

	if (timed) {
		uint64_t t = out->now();
		out->phase[TC_PHASE_ROWS] = (uint32_t)(t - phase_at);
		phase_at = t;
	}
	cull_blocks();
	if (timed) {
		uint64_t t = out->now();
		out->phase[TC_PHASE_CULL] = (uint32_t)(t - phase_at);
		phase_at = t;
	}
	int32_t cx = floor_div(cam_x, CELL), cz = floor_div(cam_z, CELL);
	int32_t z_lo = 0, z_hi = land->cells_z - 1;
	while (z_lo <= z_hi) {
		uint32_t gz = farther(&z_lo, &z_hi, cz);
		int32_t x_lo = 0, x_hi = land->cells_x - 1;
		while (x_lo <= x_hi) {
			uint32_t gx = farther(&x_lo, &x_hi, cx);
			if (block_shown[gz / BLOCK * blocks_x + gx / BLOCK] == 1) {
				draw_cell(gx, gz);
				/* The sprite is drawn as the walk reaches the cell
				 * it stands on, so the nearer land, which the walk
				 * has still to draw, paints over it and the farther
				 * land, already drawn, stays behind it. */
				if (gx == sprite_gx && gz == sprite_gz)
					draw_sprite();
			}
		}
	}

	if (timed) {
		uint64_t t = out->now();
		out->phase[TC_PHASE_WALK] = (uint32_t)(t - phase_at);
		phase_at = t;
	}

	/* How many cards to stand on the land, and the side of the square they stand
 * in. One a tile by default, which is the shelf that shows the art; more than
 * the art holds re-uses tiles, which is what a crowd is. */
#ifndef TC_CARDS_N
#define TC_CARDS_N 64
#endif

/* The four cards, standing in a row beside the sprite, one tile each,
 * drawn where the sprite is drawn so that the land in front of that
 * cell still paints over them. A card is three cells tall and as wide
 * as it is tall, and the steps it hands the fill are the tile's 32
 * texels across that width, which is the divide the fabric does not
 * have. */
#if TC_CARDS
	if (out->card != NULL) {
		uint32_t side = 1;
		while (side * side < (uint32_t)TC_CARDS_N)
			side++;
		for (uint32_t i = 0; i < (uint32_t)TC_CARDS_N; i++) {
			/* A square of them, three cells apart, standing on the
			 * ground by the island's middle. Past the art's last tile
			 * they start again from the first, which is how a crowd of
			 * one kind is drawn. */
			int32_t gx = sprite_gx - (int32_t)(side * 3 / 2) +
				     (int32_t)(i % side) * 3;
			int32_t gz = sprite_gz - (int32_t)(side * 3 / 2) +
				     (int32_t)(i / side) * 3;
			card_at(gx * CELL + CELL / 2, sprite_y, gz * CELL + CELL / 2,
				i % ART_TILES);
		}
	}
#endif

	/* The pin, if this build was given one: one card standing where it was
	 * asked to stand, on the ground of the cell it names. It is drawn wherever
	 * the camera is, which is what makes it a thing in the world rather than
	 * a thing on the screen. */
	if (TC_PIN_SET) {
		int32_t wx, wz;
		pin_world(&wx, &wz);
		card_at(wx, ground(wx, wz), wz, 0);
	}

	// The cursor goes last, so that it lies over everything else. Its middle
	// is the mouse's position, and the sprite it draws is the frame's or the
	// crosshair's depending on what is held.
	if (cam_driven) {
		unsigned which =
			(cursor_buttons &
			 (TC_MOUSE_LEFT | TC_MOUSE_MIDDLE | TC_MOUSE_RIGHT))
				? 1u : 0u;
		for (uint32_t i = 0; i < cursor_runs_used[which]; i++) {
			const struct hand_run *run = &cursor_runs[which][i];
			/* The sprite is drawn on whole framebuffer pixels. The fill keeps
			 * a pixel whose centre lies on a triangle's edge, and the
			 * midpoint is a half pixel, so a sprite placed at a whole-pixel
			 * position has every edge on a centre: one-pixel lines come out
			 * two pixels wide, and not on the same side twice. Snapping each
			 * run puts every edge on a boundary, where nothing ties. */
			int32_t ox = (cursor_x - TC_CURSOR_MID_X + 8) & ~15;
			int32_t oy = (cursor_y - TC_CURSOR_MID_Y + 8) & ~15;
			int32_t x0 = ox + run->x * 16;
			int32_t y0 = oy + run->y * 16;
			hand_rect(x0, y0, x0 + run->length * 16, y0 + 16,
				  run->colour);
		}
	}

	/* The camera readout goes with it, over everything the frame drew. */
	draw_readout();
}
